/**
 * Guardrail Action Interception Model & State Definitions
 *
 * Defines the strongly-typed data structures for tracking and managing
 * the governance lifecycle of intercepted browser actions.
 *
 * ARCHITECTURAL PRINCIPLES:
 * 1. SEPARATION OF CONCERNS:
 *    - The InterceptionRecord tracks the operational LIFECYCLE of an interaction
 *      (whether it is detected, held, continued, or cancelled).
 *    - It is strictly decoupled from:
 *      * DOM manipulation and live element bindings
 *      * Action classification (WHAT the action is)
 *      * Risk assessment scoring (HOW sensitive the action is)
 *      * Response policy selection (WHAT policy applies)
 * 2. ACTION ID PRESERVATION:
 *    - Preserves the original `actionId` generated by GuardrailAction to maintain
 *      deterministic correlation across the entire pipeline without mutating source models.
 * 3. STRICT PRIVACY & DATA ISOLATION:
 *    - Zero live DOM references (`HTMLElement`, `Node`, `Event`).
 *    - Zero sensitive user values (passwords, card numbers, OTPs, text entries).
 *    - Fully JSON-serializable for secure transmission across extension boundaries.
 * 4. DETERMINISTIC STATE TRANSITIONS:
 *    - Transitions follow a strictly bounded state machine.
 *    - Terminal states (CONTINUED, CANCELLED) cannot transition further.
 */

/**
 * Canonical lifecycle states for an intercepted browser action.
 */
export enum InterceptionState {
  /**
   * Action has been observed and captured at the browser event capture boundary.
   * Initial entry state for all evaluated interactions.
   */
  DETECTED = 'DETECTED',

  /**
   * Action has been paused and suppressed from host page execution.
   * Held pending user review (e.g. Warning Modal) or future protective gating.
   */
  HELD = 'HELD',

  /**
   * Action has been approved to continue and re-dispatched to the host page
   * with a bypass token. Terminal state.
   */
  CONTINUED = 'CONTINUED',

  /**
   * Action has been permanently cancelled, aborted, or rejected.
   * No side-effects or handlers will execute on the host page. Terminal state.
   */
  CANCELLED = 'CANCELLED',
}

/**
 * String union type representing valid InterceptionState values.
 */
export type InterceptionStateString = 'DETECTED' | 'HELD' | 'CONTINUED' | 'CANCELLED';

/**
 * Strongly typed interception record capturing the lifecycle status of an action.
 *
 * Strictly detached from DOM nodes, user inputs, and risk engine algorithms.
 */
export interface InterceptionRecord {
  /**
   * Reference to the unique identifier of the GuardrailAction being governed.
   * Strictly preserves the original actionId for end-to-end auditability.
   */
  readonly actionId: string;

  /**
   * Current governance lifecycle state of the action.
   */
  readonly state: InterceptionState;

  /**
   * ISO 8601 timestamp recording when this interception record was created.
   */
  readonly createdAt: string;

  /**
   * Optional ISO 8601 timestamp recording when the action reached a terminal state
   * (CONTINUED or CANCELLED). Undefined while in DETECTED or HELD states.
   */
  readonly resolvedAt?: string;

  /**
   * Short, human-readable explanation justifying the current lifecycle state.
   * STRICT PRIVACY: Contains policy and lifecycle rationales only; never sensitive data.
   */
  readonly reason: string;
}
